"""Lint, compile and run the frozen original testbench; decide TB status from evidence.

Status names: TB_PASSED, TB_FAILED, INCONCLUSIVE, TIMEOUT. Exit codes are recorded
but never substituted for semantic status.
"""
import re
import shutil
from collections import Counter
from pathlib import Path

from .util import run_job

ADAPTER_TAG = "RTLTRIAL_ADAPTER"


def monitor_source(mon):
    """Passive observer module: counts events and samples TB checker variables at
    end of simulation. It drives nothing, so stimulus and verdict are unchanged."""
    lines = ["// generated by rtltrial: passive log adapter, drives no signals", "module rtltrial_monitor;"]
    fmt, args = [], []
    for name, sig in mon.get("events", {}).items():
        lines += [f"  integer {name} = 0;", f"  always @(posedge {sig}) {name} = {name} + 1;"]
        fmt.append(f"{name}=%0d")
        args.append(name)
    for name, var in mon.get("values", {}).items():
        fmt.append(f"{name}=%0d")
        args.append(var)
    lines.append(f'  final $display("{ADAPTER_TAG} {" ".join(fmt)}", {", ".join(args)});')
    lines.append("endmodule")
    return "\n".join(lines) + "\n"


def lint(man, rtl_dir, rtl_files, out_dir):
    """Verilator -Wall lint. Returns errors flag and the normalized warning multiset."""
    out = Path(out_dir)
    cmd = [man["tools"]["verilator_bin"], "--lint-only", "-Wall", "-Wno-fatal", "--top-module", man["top"]]
    cmd += [f"-D{k}={v}" for k, v in man["defines"].items()]
    cmd += [str(Path(rtl_dir, f).resolve()) for f in rtl_files]
    job = run_job(cmd, out, out / "lint.log", man["tb"]["compile_timeout_s"])
    text = Path(job["log"]).read_text(errors="replace")
    warns = Counter()
    for m in re.finditer(r"^%Warning-(\w+): [^:]+:\d+:\d+: (.*)$", text, re.M):
        warns[f"{m.group(1)}: {m.group(2).strip()}"] += 1
    errors = re.findall(r"^%Error.*$", text, re.M)
    return {"job": job, "errors": errors[:20], "warnings": dict(sorted(warns.items()))}


def compile_and_run(man, rtl_dir, rtl_files, tb_dir, out_dir, timeout_s=None):
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    tbc = man["tb"]
    (out / "rtltrial_monitor.v").write_text(monitor_source(tbc["monitor"]))
    srcs = [str(Path(rtl_dir, f).resolve()) for f in rtl_files]
    srcs += [str(Path(tb_dir, f).resolve()) for f in tbc["files"]] + ["rtltrial_monitor.v"]
    cmd = [man["tools"]["iverilog_bin"], "-g2012", "-s", tbc["top"], "-s", "rtltrial_monitor",
           "-o", "sim.vvp"] + [f"-D{k}={v}" for k, v in man["defines"].items()] + srcs
    rec = {"compile_job": run_job(cmd, out, out / "compile.log", tbc["compile_timeout_s"]), "sim_job": None}
    cj = rec["compile_job"]
    if cj["timed_out"] or cj["exit_code"] != 0 or not (out / "sim.vvp").exists():
        rec.update(compile_status="COMPILE_FAILED", tb_status=None, evidence=None)
        return rec
    rec["compile_status"] = "COMPILED"
    sj = run_job([man["tools"]["vvp_bin"], "-n", "sim.vvp"], out, out / "sim.log",
                 timeout_s if timeout_s is not None else tbc["timeout_s"])
    rec["sim_job"] = sj
    status, evidence = judge(Path(sj["log"]).read_text(errors="replace"), sj, tbc["pass_contract"])
    rec.update(tb_status=status, evidence=evidence)
    return rec


_OPS = {">=": lambda a, b: a >= b, "==": lambda a, b: a == b, "<=": lambda a, b: a <= b}


def judge(log, job, pc):
    """Apply the frozen PASS contract. Every requirement must be evidenced; missing
    evidence is INCONCLUSIVE, never a default pass."""
    ev = {"exit_code": job["exit_code"], "timed_out": job["timed_out"], "elapsed_s": job["elapsed_s"]}
    if job["timed_out"]:
        return "TIMEOUT", ev
    fails = [l for l in log.splitlines() if any(re.search(r, l) for r in pc["fail_regexes"])]
    ev["fail_lines"] = fails[:10]
    fin = re.search(pc["finish_regex"], log)
    ev["finish"] = fin.group(0) if fin else None
    ev["sim_time"] = int(fin.group(1)) if fin and fin.groups() else None
    pas = re.search(pc["pass_regex"], log)
    ev["pass_marker"] = pas.group(0) if pas else None
    ad = re.search(rf"^{ADAPTER_TAG} (.*)$", log, re.M)
    adapter = {k: int(v) for k, v in re.findall(r"(\w+)=(-?\d+)", ad.group(1))} if ad else None
    ev["adapter"] = adapter
    if fails:
        return "TB_FAILED", ev
    unmet = []
    for field, (op, val) in pc["adapter_requirements"].items():
        got = (adapter or {}).get(field)
        if got is None or not _OPS[op](got, val):
            unmet.append(f"{field}={got} not {op} {val}")
            if got is not None and field in pc.get("adapter_failure_fields", []):
                ev["unmet"] = unmet
                return "TB_FAILED", ev
    ev["unmet"] = unmet
    if job["exit_code"] != 0:
        ev["reason"] = "simulator nonzero exit without a failure marker"
        return "INCONCLUSIVE", ev
    if not fin or not pas or adapter is None or unmet:
        ev["reason"] = "missing evidence: " + ", ".join(
            x for x, ok in [("finish", fin), ("pass_marker", pas), ("adapter", adapter is not None),
                            ("adapter_requirements", not unmet)] if not ok)
        return "INCONCLUSIVE", ev
    return "TB_PASSED", ev


def copy_tree(files, src_dir, dst_dir):
    for f in files:
        d = Path(dst_dir) / f
        d.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(Path(src_dir) / f, d)
